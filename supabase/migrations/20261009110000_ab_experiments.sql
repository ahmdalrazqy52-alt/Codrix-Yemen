-- Basic first-party A/B experiments for the hero heading and CTA labels.
CREATE TABLE IF NOT EXISTS public.site_experiments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  target text NOT NULL CHECK (target IN ('hero_title','hero_primary_cta','hero_secondary_cta')),
  variant_a text NOT NULL,
  variant_b text NOT NULL,
  active boolean NOT NULL DEFAULT false,
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.site_experiments ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "public_read_active_experiments" ON public.site_experiments;
CREATE POLICY "public_read_active_experiments" ON public.site_experiments FOR SELECT TO anon, authenticated USING (active = true);
DROP POLICY IF EXISTS "admins_read_all_experiments" ON public.site_experiments;
CREATE POLICY "admins_read_all_experiments" ON public.site_experiments FOR SELECT TO authenticated USING (EXISTS (SELECT 1 FROM public.admin_users WHERE user_id=auth.uid() AND active=true));
DROP POLICY IF EXISTS "admins_insert_experiments" ON public.site_experiments;
CREATE POLICY "admins_insert_experiments" ON public.site_experiments FOR INSERT TO authenticated WITH CHECK (EXISTS (SELECT 1 FROM public.admin_users WHERE user_id=auth.uid() AND active=true) AND created_by=auth.uid());
DROP POLICY IF EXISTS "admins_update_experiments" ON public.site_experiments;
CREATE POLICY "admins_update_experiments" ON public.site_experiments FOR UPDATE TO authenticated USING (EXISTS (SELECT 1 FROM public.admin_users WHERE user_id=auth.uid() AND active=true)) WITH CHECK (EXISTS (SELECT 1 FROM public.admin_users WHERE user_id=auth.uid() AND active=true));
DROP POLICY IF EXISTS "admins_delete_experiments" ON public.site_experiments;
CREATE POLICY "admins_delete_experiments" ON public.site_experiments FOR DELETE TO authenticated USING (EXISTS (SELECT 1 FROM public.admin_users WHERE user_id=auth.uid() AND active=true));
GRANT SELECT ON public.site_experiments TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.site_experiments TO authenticated;

CREATE TABLE IF NOT EXISTS public.site_experiment_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  experiment_id uuid NOT NULL REFERENCES public.site_experiments(id) ON DELETE CASCADE,
  variant text NOT NULL CHECK (variant IN ('a','b')),
  event_type text NOT NULL CHECK (event_type IN ('impression','click')),
  visitor_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (experiment_id, visitor_id, event_type)
);
ALTER TABLE public.site_experiment_events ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "public_record_experiment_events" ON public.site_experiment_events;
CREATE POLICY "public_record_experiment_events" ON public.site_experiment_events FOR INSERT TO anon, authenticated
WITH CHECK (length(visitor_id) BETWEEN 8 AND 100 AND EXISTS (SELECT 1 FROM public.site_experiments e WHERE e.id=experiment_id AND e.active=true));
DROP POLICY IF EXISTS "admins_read_experiment_events" ON public.site_experiment_events;
CREATE POLICY "admins_read_experiment_events" ON public.site_experiment_events FOR SELECT TO authenticated
USING (EXISTS (SELECT 1 FROM public.admin_users WHERE user_id=auth.uid() AND active=true));
GRANT INSERT ON public.site_experiment_events TO anon, authenticated;
GRANT SELECT ON public.site_experiment_events TO authenticated;
